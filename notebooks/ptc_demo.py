def show_execution(result):
    """Show the actual program and routing metadata without dumping expense payloads."""
    counts = Counter(item['call']['name'] for item in result['tool_results'])
    print(f"{result['approach']} · {len(SCHEMAS)} tools available · "
          f"{result['model_requests']} API requests · {result['tool_invocations']} Python tool calls · "
          f"correct={result['correctness']}")
    display({tool['name']: counts[tool['name']] for tool in SCHEMAS})
    display(Markdown('**Question, rules and orchestration instruction sent to the model:**'))
    display(Code(result['prompt'], language='text'))
    if result['programs']:
        display(Markdown('**Code generated by the model and executed by OpenAI:**'))
        display(Code(result['programs'][0], language='javascript'))
    display(Markdown('**Actual tool handoffs (payloads stay in the audit JSON):**'))
    display([dict(tool=item['call']['name'], arguments=item['call']['arguments'],
                  caller=item['call'].get('caller', {}).get('type', 'direct'),
                  result_destination=item['destination'],
                  result_characters=len(item['reply']['output']))
             for item in result['tool_results']])
    program_outputs = [item['result'] for response in result['responses']
                       for item in response['output'] if item['type'] == 'program_output']
    if program_outputs:
        display(Markdown('**Compact result emitted by the hosted program:**'))
        display(Code(program_outputs[-1], language='json'))
    display(Markdown('**Final answer:**'))
    display(result['answer'])


def show_benchmark_paths(runs):
    for approach in ('standard', 'ptc'):
        example = next((r for r in runs if r['approach'] == approach), None)
        if example:
            show_execution(example)


def log_mlflow_results(runs, dataset, source='live'):
    import mlflow

    for result in runs:
        repetition = result.get('repetition', 1)
        params = {'dataset': dataset, 'approach': result['approach'],
                  'model': result['requested_model'], 'repetition': repetition,
                  'source': source}
        params.update({f"data_{key}": value
                       for key, value in result.get('dataset_config', {}).items()})
        metrics = {'correctness': int(bool(result.get('correctness'))),
                   'usage_complete': int(bool(result.get('usage_complete'))),
                   'model_requests': result.get('model_requests', 0),
                   'tool_invocations': result.get('tool_invocations', 0)}
        if result.get('elapsed_seconds') is not None:
            metrics['elapsed_seconds'] = result['elapsed_seconds']
        if result.get('usage_complete'):
            metrics.update({key: value for key, value in result.get('usage', {}).items()
                            if value is not None and key != 'cached_input_tokens'})
        tags = {'returned_models': ','.join(result.get('returned_models', []))}
        if result.get('error'):
            tags['error_type'] = result['error'].get('type', 'unknown')

        with mlflow.start_run(
                run_name=f"{source}-{dataset}-{result['approach']}-r{repetition}"):
            mlflow.log_params(params)
            mlflow.set_tags(tags)
            mlflow.log_metrics(metrics)


