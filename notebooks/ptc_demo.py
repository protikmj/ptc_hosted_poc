def show_execution(result):
    """Show the actual program and routing metadata without dumping expense payloads."""
    print(f"{result['approach']} · {result['model_requests']} model requests · "
          f"{result['tool_invocations']} Python tool calls · correct={result['correctness']}")
    display(Markdown('**Question, rules and orchestration instruction sent to the model:**'))
    display(Code(result['prompt'], language='text'))
    if result['programs']:
        display(Markdown('**Code generated by the model and executed by OpenAI:**'))
        display(Code(result['programs'][0], language='javascript'))
    display(Markdown('**Actual tool handoffs (payloads stay in the audit JSON):**'))
    display([dict(tool=item['call']['name'], arguments=item['call']['arguments'],
                  caller=item['call'].get('caller', {}).get('type', 'direct'),
                  result_destination=item['destination'],
                  result_characters=len(item['reply']['output']))
             for item in result['tool_results']])
    program_outputs = [item['result'] for response in result['responses']
                       for item in response['output'] if item['type'] == 'program_output']
    if program_outputs:
        display(Markdown('**Compact result emitted by the hosted program:**'))
        display(Code(program_outputs[-1], language='json'))
    display(Markdown('**Final answer:**'))
    display(result['answer'])


def show_benchmark_paths(runs):
    for approach in ('standard', 'ptc'):
        example = next((r for r in runs if r['approach'] == approach), None)
        if example:
            show_execution(example)

